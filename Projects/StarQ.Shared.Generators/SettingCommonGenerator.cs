using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using StarQ.Shared.Generators;

[Generator]
public sealed class SettingCommonGenerator : IIncrementalGenerator
{
    private const string AttributeFullName =
        "StarQ.Shared.Generators.GenerateSettingCommonAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeFullName,
            predicate: static (node, _) => node is ClassDeclarationSyntax,
            transform: static (ctx, _) => (ClassDeclarationSyntax)ctx.TargetNode
        );

        var compilationAndClasses = context.CompilationProvider.Combine(candidates.Collect());

        context.RegisterSourceOutput(
            compilationAndClasses,
            static (spc, source) =>
            {
                var (compilation, classes) = source;

                foreach (var classDecl in classes.Distinct())
                {
                    var model = compilation.GetSemanticModel(classDecl.SyntaxTree);
                    var symbol = model.GetDeclaredSymbol(classDecl);
                    if (symbol is null)
                        continue;

                    var ns = symbol.ContainingNamespace.IsGlobalNamespace
                        ? null
                        : symbol.ContainingNamespace.ToDisplayString();

                    var className = symbol.Name;
                    var idValue = ns ?? className;

                    bool hasManualTabOrder = AttributeHelper.HasAttribute(
                        symbol,
                        "SettingsUITabOrderAttribute"
                    );
                    bool hasManualShowGroupName = AttributeHelper.HasAttribute(
                        symbol,
                        "SettingsUIShowGroupNameAttribute"
                    );

                    string SettingsUITabOrder = string.Empty;
                    string SettingsUIShowGroupName = string.Empty;
                    if (!hasManualTabOrder)
                    {
                        SettingsUITabOrder = "[SettingsUITabOrder(GeneralTab, AboutTab, LogTab)]";
                    }
                    if (!hasManualShowGroupName)
                    {
                        SettingsUIShowGroupName = "[SettingsUIShowGroupName(AboutModGroup)]";
                    }

                    string code = Build(ns, SettingsUITabOrder, SettingsUIShowGroupName);

                    spc.AddSource($"SettingCommonGenerator.g.cs", code);
                }
            }
        );
    }

    static string Build(string ns, string SettingsUITabOrder, string SettingsUIShowGroupName)
    {
        return $@"// <auto-generated/>
using Colossal.IO.AssetDatabase;
using Colossal.Json;
using Game.Modding;
using Game.Settings;
using Game.UI.Localization;
using StarQ.Shared.Extensions;

namespace {ns}
{{
    [FileLocation(""ModsSettings\\StarQ\\"" + nameof({ns}))]
    {SettingsUITabOrder}
    {SettingsUIShowGroupName}
    public partial class Setting
    {{
        public Setting(IMod mod)
            : base(mod) => SetDefaults();

        public const string GeneralTab = ""GeneralTab"";
        public const string GeneralGroup = ""GeneralGroup"";

        public const string AboutTab = ""AboutTab"";
        public const string InfoGroup = ""InfoGroup"";
        public const string AboutModGroup = ""AboutModGroup"";

        public const string LogTab = ""LogTab"";

        public static LocalizedString TitleText =>
            LocalizedString.Id($""<{{Mod.Name}}> ({{VariableHelper.AddDevSuffix(Mod.Version)}}) by **{{VariableHelper.StarQ}}**"");

        [SettingsUIMultilineText]
        [SettingsUIDisplayName(typeof(Setting), nameof(TitleText))]
        [SettingsUISection(AboutTab, InfoGroup)]
        public string Title => string.Empty;

        [SettingsUIButton]
        [SettingsUIButtonGroup(""Social1"")]
        [SettingsUISection(AboutTab, InfoGroup)]
        public bool BMaCLink
        {{
            set => VariableHelper.OpenBMAC();
        }}

        [SettingsUIButton]
        [SettingsUIButtonGroup(""Social1"")]
        [SettingsUISection(AboutTab, InfoGroup)]
        public bool ParadoxForum
        {{
            set => VariableHelper.OpenParadoxForum();
        }}

        [SettingsUIButton]
        [SettingsUIButtonGroup(""Social2"")]
        [SettingsUISection(AboutTab, InfoGroup)]
        [SettingsUIDisplayName(overrideValue: ""CSM Discord"")]
        [SettingsUIDescription(overrideValue: ""Cities: Skylines Modding Discord Server"")]
        public bool CSMDiscord
        {{
            set => VariableHelper.OpenCSMDiscord(Mod.Id);
        }}

        [SettingsUIButton]
        [SettingsUIButtonGroup(""Social2"")]
        [SettingsUISection(AboutTab, InfoGroup)]
        [SettingsUIDisplayName(overrideValue: ""StarQ Discord"")]
        [SettingsUIDescription(overrideValue: ""StarQ Discord Server"")]
        public bool StarQDiscord
        {{
            set => VariableHelper.OpenStarQDiscord();
        }}

        public static LocalizedString AboutModText =>
            LocalizedString.Id(StarQ.Shared.Markdown.LongDescription);

        [SettingsUIMultilineText]
        [SettingsUIDisplayName(typeof(Setting), nameof(AboutModText))]
        [SettingsUISection(AboutTab, AboutModGroup)]
        public string AboutMod => string.Empty;

        //public static LocalizedString ChangelogText =>
        //    LocalizedString.Id(StarQ.Shared.Markdown.ChangeLog);

        //[SettingsUIMultilineText]
        //[SettingsUIDisplayName(typeof(Setting), nameof(ChangelogText))]
        //[SettingsUISection(AboutTab, """")]
        //public string Changelog => string.Empty;

        private bool _debugLogging;

        [SettingsUIDisplayName(overrideValue: ""Enable Debug Logging"")]
        [SettingsUIDescription(
            overrideValue: ""Enable debug logging for troubleshooting. Disable it afterward.""
        )]
        [SettingsUISection(LogTab, ""1"")]
        public bool DebugLogging
        {{
            get => _debugLogging;
            set
            {{
                _debugLogging = value;
                LogHelper.ReleaseDebug = value;
                StarQHelper.SendDebugNotification(value);
                LogHelper.SendLog($""Debug Logging {{(value ? ""enabled"" : ""disabled"")}}"");
                
            }}
        }}

        [SettingsUIButton]
        [SettingsUIDisableByCondition(typeof(Setting), nameof(IsLogMissing))]
        [SettingsUISection(LogTab, ""2"")]
        public bool OpenLog
        {{
            set => LogHelper.OpenLogFile();
        }}

        [SettingsUIMultilineText]
        [SettingsUIDisplayName(typeof(LogHelper), nameof(LogHelper.LogText))]
        [SettingsUISection(LogTab, ""2"")]
        public string LogText => string.Empty;

        [Exclude]
        [SettingsUIHidden]
        public bool IsLogMissing
        {{
            get => LogHelper.CheckLogFile();
        }}
    }}
}}";
    }
}
