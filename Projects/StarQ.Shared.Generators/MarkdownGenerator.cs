using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

[Generator]
public sealed class MarkdownGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<AdditionalText> markdownFiles =
            context.AdditionalTextsProvider.Where(file =>
                Path.GetExtension(file.Path).Equals(".md", StringComparison.OrdinalIgnoreCase)
            );

        context.RegisterSourceOutput(markdownFiles, Generate);
    }

    private static void Generate(SourceProductionContext context, AdditionalText file)
    {
        string markdown = file.GetText(context.CancellationToken)?.ToString() ?? "";
        markdown = ConvertMarkdown(markdown);

        string literal = SyntaxFactory
            .LiteralExpression(
                Microsoft.CodeAnalysis.CSharp.SyntaxKind.StringLiteralExpression,
                SyntaxFactory.Literal(markdown)
            )
            .ToFullString();

        string propertyName = Path.GetFileNameWithoutExtension(file.Path);

        string source =
            $@"// <auto-generated/>

namespace StarQ.Shared
{{
    public static partial class Markdown
    {{
        public static string {propertyName} => {literal};
    }}
}}";

        context.AddSource($"{propertyName}.g.cs", SourceText.From(source, Encoding.UTF8));
    }

    private static string ConvertLine(string line)
    {
        if (line.StartsWith("* "))
            return "- " + line.Substring(2);

        if (line.StartsWith("### "))
            return $"**{line.Substring(4)}**";

        return line;
    }

    private static string ConvertMarkdown(string markdown)
    {
        return string.Join(
            "\n",
            markdown.Split(["\r\n", "\n"], StringSplitOptions.None).Select(ConvertLine)
        );
    }
}
