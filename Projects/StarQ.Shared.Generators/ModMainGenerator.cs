using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

[Generator]
public class ModMainGenerator : IIncrementalGenerator
{
    private const string AttributeFullName = "StarQ.Shared.Generators.GenerateModInfoAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeFullName,
            predicate: static (node, _) => node is ClassDeclarationSyntax,
            transform: static (ctx, _) => (ClassDeclarationSyntax)ctx.TargetNode
        );

        var compilationAndClasses = context.CompilationProvider.Combine(candidates.Collect());

        context.RegisterSourceOutput(
            compilationAndClasses,
            static (spc, source) =>
            {
                var (compilation, classes) = source;

                foreach (var classDecl in classes.Distinct())
                {
                    var model = compilation.GetSemanticModel(classDecl.SyntaxTree);
                    var symbol = model.GetDeclaredSymbol(classDecl);
                    if (symbol == null)
                        continue;

                    var ns = symbol.ContainingNamespace.IsGlobalNamespace
                        ? null
                        : symbol.ContainingNamespace.ToDisplayString();

                    var className = symbol.Name;
                    var idValue = ns ?? className;

                    string code =
                        $@"// <auto-generated/>
using Colossal.IO.AssetDatabase;
using Colossal.Json;
using Colossal.Logging;
using Colossal.PSI.Environment;
using Game.Modding;
using Game.Settings;
using Game.UI.Localization;
using StarQ.Shared.Extensions;
using System.Reflection;

namespace {ns}
{{
    public partial class {className}
    {{
        public static Mod Instance;
        public static string Id = ""{idValue}"";
        public static string Name = Assembly
            .GetExecutingAssembly()
            .GetCustomAttribute<AssemblyTitleAttribute>()
            .Title;
        public static string Version = Assembly
            .GetExecutingAssembly()
            .GetName()
            .Version.ToString(3);
        public static string DataDir = $""{{EnvPath.kUserDataPath}}\\ModsData\\{{Id}}"";
        public static ILog log = LogManager.GetLogger($""{{Id}}"").SetShowsErrorsInUI(true);
        public static Setting m_Setting;
    }}
}}";

                    spc.AddSource($"ModMainGenerator.g.cs", code);
                }
            }
        );
    }
}
